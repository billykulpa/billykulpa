<h2>Logo development</h2>
<p>The CEO liked the idea of incorporating "screens" (or perhaps <em>"windows"</em>) into the logo. The concept was that Netreo's core function is to provide organizations with windows into their IT environment. Users observe their systems through dashboards and take action when necessary. So, I began by sketching different configurations of squares.</p>
<p>I combined the idea of screens with the notion of upward trajectory to arrive at the final approved logo. Each square was 25% smaller than the one after it, implying more visibility the more the user digs in. The squares could stand alone as an icon and could appear in the brand colors, black, or white.</p>
<p>From there, I explored a wide range of typefaces before settling on custom lettering built from circles, ovals, and lines. I’ve said that before, but it’s my M.O. Each character is based on simple geometric shapes, which felt both clever and efficient.</p>
