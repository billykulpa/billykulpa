<p>I wanted a more round, more "chubby" wordmark for the primary logo. We slightly tweaked the blue, moving from a paler shade to something more vibrant, and dropped the yellow altogether. A tagline was added down the line, set in a pewter color.</p>

<h2>Website development</h2>
<p>The retail website that I was tasked with replacing used a custom PHP base with no CMS, which meant only IT could update content. For the revamp, we went with WordPress. Our goal was to open up content editing to multiple people within the company without relying a developer for day-to-day updates. This was especially important for areas of the site like <em>Custom Connectors</em>. Hundreds were added over the life of the website.</p>
<p>I developed the CMS with <a href="https://www.advancedcustomfields.com/" target="_blank" title="Visit the Advanced Custom Fields website">Advanced Custom Fields</a>, structuring it around flexible content blocks that the team could edit without worry. Each page or post could be built from a series of vertical modules (either assembled from existing patterns or created as entirely custom sections), giving the site a consistent but adaptable framework.</p>
<p>On the performance side, I focused on keeping the codebase lean. Replacing jQuery with plain JavaScript helped reduce weight and improve load times, contributing to strong results in Google PageSpeed Insights.</p>
<p>Site animations, including several interactive SVG elements, were implemented using a mix of CSS and JavaScript. This approach kept the interface lively while maintaining efficient performance and avoiding unnecessary bloat.</p>

