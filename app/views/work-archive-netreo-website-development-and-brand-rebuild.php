<p>In the spring of 2019, I was approached by Netreo, a B2B software company headquartered in Bakersfield, California, to lead a comprehensive website initiative. At the time, the company was looking to modernize its identity to better reflect its growth, capabilities, and evolving position in the enterprise IT space. It was determined that redesigning the website from the ground up was the best avenue to complete this objective.</p>
<p>Netreo needed a website that would resonate more clearly with their target audience and support their expanding product offerings. After the project kicked off, the scope was expanded to include a new logo and supporting brand materials.</p>
<p>In 2024, Netreo was acquired by <a href="https://www.bmc.com/" target="_blank" title="Visit the BMC website">BMC</a>.</p>
