<p>Ideally, the brand supports the entire journey. It should give people a sense of clarity and confidence, helping them feel understood and guided from the first hello through the final decision.</p>
<p>My work with Cleo represented my largest end-to-end branding project at the time. I developed the website, created the logo, and produced all supporting materials myself, which gave me the opportunity to build a cohesive brand from the ground up. There were no vendors involved. I learned to both edit videos and animate. It was a challenging and rewarding project that helped refine my process and broaden my capabilities.</p>
