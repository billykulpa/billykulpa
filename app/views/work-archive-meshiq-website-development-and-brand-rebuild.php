<p>In the fall of 2022, I was contacted by Nastel Technologies about a rebranding opportunity. They were changing their name to MeshIQ and needed a new logo, website, and a collection of supporting assets to reflect the update. Rebrands like this don't come around often, so it was important to create a visual identity with long-term staying power.</p>
<p>The centerpiece of the rebrand was the logo and website, but the project also included lower-stakes print materials such as business cards, letterhead, and email signatures. On the digital side, I created assets like PowerPoint templates, animated SVGs, and branded case studies.</p>
