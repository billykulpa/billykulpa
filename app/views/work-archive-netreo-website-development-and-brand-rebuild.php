<h2>Project kickoff</h2>
<p>Netreo is a California-based software company that monitors I.T. activity across the entire organization without needing to install software on every device. Here's the company description as of this writing:</p>
<blockquote>
<p>Netreo is an IT infrastructure monitoring platform that helps organizations keep track of everything from servers and networks to cloud services and applications. It provides a complete, real-time view of your entire IT environment, without needing to install software agents on every device. Netreo monitors system performance, tracks network traffic, checks application availability, and alerts teams to issues before they become problems. It also logs configuration changes and offers customizable dashboards for easy visibility.</p>
</blockquote>
<p>The engagement with Netreo began as a website redesign. But as the project team explored layout, usability, and content structure, it became clear that core brand elements (color, typography, tone, and more) would need to evolve in order to support the new direction. What began as a focused digital project quickly expanded into a full-scale rebrand.</p>
<p><strong>The goal was to position Netreo as a modern, enterprise-ready solution</strong> while maintaining its reputation for simplicity and clarity. From there, the work extended to sales collateral, PowerPoint templates, iconography, and a refreshed logo.</p>
<p>My job was to create a unified, scalable brand system across all customer touchpoints.</p>

