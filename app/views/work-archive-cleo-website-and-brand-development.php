<h2>Brand development</h2>
<p>Most of Cleo's competitors at the time operated in a creative space that I refer to as "The Matrix". That style featured a lot of green 0s and 1s floating around in digital spaces. Nothing felt authentic or personal. There was no human connection.</p>
<p>I decided to pitch humanism as a core tennant of the Cleo brand. Some of our brand keywords included <em>Friendly</em>, <em>Easy</em>, <em>Simple</em>, and <em>Professional</em>. We weren't trying to be the used car salesman dazzling you with impractical features. We wanted to be the trusted and reliable older brother who would give you good advice. We wanted to be someone you could count on.</p>
<p>Cleo's name is actually <a href="https://iokevins.blogspot.com/2015/01/cleo-cleo-cleo.html" target="_blank" title="Learn about the history of Cleo's brand">an acronym</a>. It stands for "<strong>CL</strong>uster <strong>E</strong>nvironment <strong>O</strong>perator". The logo at the time represented that, set in all caps with bars on either side of the E. My first step was updating the logo.</p>
