<p>In 2012, I shot one still photograph each day for six weeks of the Japanese garden at the Rosecrance Griffin Williamson campus. The stills were then stitched together for a timelapse video. There also is a short video segment at the end to show off the beautiful sunset behind the garden.</p>
<p>The concept was inspired by the writing of a former substance abuse patient, and was designed to showcase the transformation of the Rosecrance Healing Garden at the Griffin Williamson Campus. The metaphor is that it takes about six weeks for the garden to transition from winter to spring, the same length of time as the average inpatient treatment stay for an adolescent.</p>
<p>The garden itself is quite beautiful. The company uses it to showcase the quality of their facilities.</p>
<p>The narration component of the video was written by an adolescent in treatment at Rosecrance in the spring of 2011 and read by a patient in the spring of 2012.</p>
<blockquote class="longform">
<p>When I first got here, we were still in the final stages of winter</p>
<p>Everything was still kind of dead, and I was dead to myself</p>
<p>Then as spring began, and things started growing, I was growing in myself</p>
<p>I was learning what the root cause of my addiction was, and how to handle it</p>
<p>Meditating in the garden brings peace to my thoughts, and my heart</p>
<p>As the Healing Garden changes, people change, too.</p>
</blockquote>
<p>The video was edited in Adobe Premiere, with overlays and titles added in Adobe After Effects.</p>
