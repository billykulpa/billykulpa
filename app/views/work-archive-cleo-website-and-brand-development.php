<h2>Conclusion</h2>
<p>I think a customer's experience with a company should feel consistent no matter where it begins. Someone might start with a business card, move into an email thread, sit through a presentation, watch a product walkthrough, explore the website, and eventually reach a contract. Every one of those steps contributes to their impression of the brand.</p>
<p>On some level, I was involved at nearly every step.</p>

