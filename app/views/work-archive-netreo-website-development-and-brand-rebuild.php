<p>The Netreo website was a complete rebuild, from design and structure to content and code. While some of the original site's architecture for products and solutions carried over, nearly everything else started fresh, including the theme and copy.</p>
<p>This project became a blueprint for how I approach contract web development. Knowing I wouldn't be managing the site long-term, I focused on making it easy for Netreo's internal marketing team to take over. Since the team was already comfortable with WordPress, I developed a custom theme tailored to their workflows.</p>
<p>While the site's blog used WordPress' built-in WYSIWYG editor, the main site pages relied on the code editor, meaning editors had to drop raw markup directly into the page. That experience taught me a lasting lesson: content editors should never have to touch HTML just to make routine updates. It's become a core philosophy of mine: If editors need to dive into the codebase to do their jobs, then I haven't done mine properly.</p>
<p>This was also the project where I began prioritizing Google PageSpeed Insights scores. To boost performance, I removed WordPress's default jQuery dependency and rewrote the interactive features using lightweight vanilla JavaScript.</p>
<p>Animations, including interactive SVGs, were handled with a mix of CSS and vanilla JS, striking a balance between visual appeal and fast load times.</p>
