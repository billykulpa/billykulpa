<h2>Website development</h2>
<p>For the MeshIQ website rebuild, I approached the project with long-term maintainability in mind. As a contractor who wouldn't be around post-launch, I kept their WordPress installation as the platform so the full-time team could easily manage and update content without relying on a developer for day-to-day website updates.</p>
<p>I built the site primarily using <a href="https://www.advancedcustomfields.com/" target="_blank" title="Visit the Advanced Custom Fields website">Advanced Custom Fields (ACF)</a> to create intuitive, custom-editable sections that empowered the team to make changes with confidence. Vertical sections could added to any page or post, with options to build out a section from scratch or work from a library of pre-built modules.</p>
<p>From a performance perspective, I prioritized a high score on Google PageSpeed Insights by removing jQuery in favor of lightweight, vanilla JavaScript.</p>
<p>Animations throughout the site (including several interactive SVGs) were handled with a combination of CSS and JavaScript to ensure both visual engagement and minimal overhead.</p>
