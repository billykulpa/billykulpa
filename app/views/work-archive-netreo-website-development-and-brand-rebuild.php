<h2>Page philosophy and examples</h2>
<p>The visual design leans into a bright, West Coast-inspired palette, paired with a set of flexible brand patterns that translated seamlessly to print. The website should perfectly match everything from case studies to sales collateral.</p>
<p>I also created a series of stylized vector product screenshots. The goal was to highlight Netreo's clean UI while avoiding the versioning issues that come with literal screenshots. The result felt both recognizable and future-proof.</p>
