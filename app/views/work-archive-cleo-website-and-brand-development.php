<p>I worked full-time for Cleo as the Senior Manager for Creative and Web from 2013 to 2018. During that time, I was given a tremendous opportunity to rebrand the company from the ground up.</p>
<p>I led the development of a complete visual identity (logo, typography, color palette, photography standards, and motion graphics) while defining a clearer, more consistent tone and voice. I designed and developed the website without a vendor. I animated lead generation videos. I shot photos of company events, and leadership still uses staff headshots I took. It remains one of the most rewarding and formative chapters of my career.</p>
