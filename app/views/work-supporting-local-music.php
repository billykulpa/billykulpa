      <div class="prose">
        <p>This was the one that started the run. My friends are in a
        Rockford-based Midwest emo band called Joie de Vivre, and when they
        booked a show at Mary&rsquo;s Place with Burgess Shale and Chai Teeth,
        I offered to design the poster.</p>
        <p>The bear started life as an open-source vector I found online. I
        modified it heavily, building the space suit out of other vectors,
        layering everything with a lot of opacity tricks over a kraft-paper
        texture, and then laying it out like a traditional gig poster:
        date and price up top, bands in the middle, venue at the bottom.
        Honestly, it wasn&rsquo;t that different from what I do for my day
        job: same grid instincts, same typographic hierarchy, more fun
        subject matter.</p>

