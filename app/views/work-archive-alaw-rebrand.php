<h2>The digital campaign</h2>
<p>Where the system earns its keep is volume. Every season, the identity has
to ship as programmatic display in every standard size, paid social, speaker
announcements, email graphics, event listings, and web heroes, and read as
ALAW at 320&times;50 just as clearly as it does on a program book cover. The
motif was built for that: the laser streaks and letterforms survive any crop,
any aspect ratio, any duration.</p>

