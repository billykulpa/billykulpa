<h2>Begin at the beginning</h2>
<p>Cleo is the rarely seen 50-year-old software company. The company was formed in 1976 in my home town of Rockford, Illinois, which might be even more rare. They initially focused on hardware: data concentrators, modems, and terminal emulators to connect with IBM mainframes. As the company matured, it pivoted into software.</p>
<p>In the 1980s, their focus was on mainframe middleware, and by the time I got there in 2012, Cleo was working on secure B2B data transfer, file-transfer, and EDI solutions.</p>
<p>Here's Cleo's elevator pitch at the time of this writing:</p>
<blockquote>
<p>Go beyond basic integration with the only supply chain orchestration platform offering AI-powered no-code onboarding, intelligent issue resolution, and proactive visibility.</p>
</blockquote>
<p>I joined the company shortly after it was acquired by a private equity group. The mandate was to modernize the brand. We needed to compete against significantly bigger players in the software space. My job was to make a 50-person, $5M company look and feel like a 500-person, $50M company.</p>

