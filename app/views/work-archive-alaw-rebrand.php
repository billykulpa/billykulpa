<p>The Advanced Laser Applications Workshop (ALAW) is a long-standing annual conference that showcases the latest advancements and applications of lasers in the fabricating and manufacturing industries. It's one of the many sub-brands, events, and other properties we have at <a href="https://www.fmamfg.org/" target="_blank" title="Visit the website of Fabricators and Manufacturers Association">FMA</a>.</p>
<p>ALAW was one of the first properties I circled for a rebrand when I got promoted to creative manager at the tail end of 2023. The idea of doing something interesting with lasers in the logo seemed like a no-brainer. Additionally, I thought the typography from the previous logo left a lot to be desired.</p>
<p>Specifically, I hated the way the 'A' and 'W' in ALAW were set at different angles:</p>
<figure class="mid-content">

<picture>
<img alt="The ALAW 2023 branding" height="131.69" src="/assets/img/logo-alaw-2023-with-markup.svg" width="448.66"/>
</picture>
<figcaption>The previous ALAW logo, which existed until the end of 2023.</figcaption>

</figure>
<p>I wasn't in love with the placement of either the FMA logo or the 2023, either.</p>
<p>I began the process by drawing custom letters, putting everything on a 100-point grid and trying my best to build characters in increments of five and 10. For the angle, I went with 30 degrees across the board. And for the descriptive text underneath the display letters, I chose the extra bold weight of Inter, the font family we use body copy and for the majority of the company's sub-brand logos.</p>
