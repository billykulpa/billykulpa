<h2>Project kickoff</h2>
<p>At its core, MeshIQ develops software that monitors business activity. Of course, there's more to it than that. Here's the company description as of this writing:</p>
<blockquote>
<p>MeshIQ is a middleware observability and management platform that helps IT organizations and business executives gain insights into and manage their digital environments. It provides tools for monitoring, analyzing, and managing messaging middleware, event processing, and streaming platforms. MeshIQ enables proactive identification of performance bottlenecks and outages, and facilitates root cause analysis.</p>
</blockquote>
<p>Software companies are notorious for writing paragraphs like this. I chose to focus on the core idea behind the pitch: <strong>observation</strong>.</p>
<p>When working on a rebranding project like this, I like to start with the logo: it sets the tone for the entire visual identity. The concept of observation brought owls to mind. The classic symbol of wisdom felt like a perfect metaphor for predictive IT software, and the visual of oversized eyes made the direction feel obvious.</p>

