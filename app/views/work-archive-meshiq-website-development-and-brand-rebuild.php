<h2>Logo development</h2>
<p>Once you have a broad theme, you can begin selecting elements that reinforce it. For example, I initially chose a color palette of navy, midnight blue, and purples, fitting choices for a nocturnal creature like the owl.</p>
<p>I didn't have a clear initial concept for the owl icon itself. I sketched (and downloaded) more than 50 owl designs before hitting a wall and shifting my focus to typography.</p>
<p>From there, I experimented with all kinds of typefaces before landing on custom lettering built from circles and lines. With only six letters in the name, it wasn't too difficult to construct. Each character is based on two simple shapes, which felt both clever and efficient.</p>
<p>The real eureka moment came when I realized I could build the owl icon from the same shape used in the "Q" of the wordmark.</p>
